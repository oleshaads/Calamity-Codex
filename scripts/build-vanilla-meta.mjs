#!/usr/bin/env node
/** Build compact semantic metadata for every classified vanilla Terraria item.
 * Source: natan-dot-com/Terraria-Dataset@51d0b5f1e83c971d16d76e7cbb1364cb3f07d19e
 * Usage: node scripts/build-vanilla-meta.mjs <items_data directory> [output.js]
 */
import fs from "node:fs";
import path from "node:path";

const input = path.resolve(process.argv[2] || "../Terraria-Dataset/json/items_data");
const output = path.resolve(process.argv[3] || "calamity-codex/js/vanilla-meta.js");
if (!fs.existsSync(input)) throw new Error(`Items-data directory is missing: ${input}`);

const FIELDS = [
  "Tooltip", "Damage", "Defense", "Mana", "Pickaxe power", "Hammer power", "Axe power",
  "Fishing Power", "Bait Power", "Reach", "Hooks", "Latching", "Buff", "Buff tooltip",
  "Debuff", "Debuff tooltip", "Duration", "Summons", "Event", "Effect", "Environment",
  "Biome", "Height", "Notes", "Bonus", "Description", "Body slot", "Creates", "Planted In",
  "Light Pet", "Brightness", "Catch Quality", "Placeable"
];
const CATEGORY_PRIORITY = [
  "miscellaneous", "furniture", "background", "block", "brick", "painting", "light_source",
  "storage", "crafting_material", "fishing_catches", "food", "potion", "consumable", "dye",
  "vanity", "accessory", "ammunition", "weapon", "armor", "tool", "bait", "critter", "seeds",
  "quest_fish", "grab_bag", "key", "pylon", "gem", "ore", "hook", "shield", "light_pet",
  "event_summon", "boss_summon"
];
const rank = new Map(CATEGORY_PRIORITY.map((name, index) => [name, index]));
const records = new Map();
const files = fs.readdirSync(input).filter((name) => /^items_.+\.json$/.test(name)).sort();
for (const file of files) {
  const category = file.replace(/^items_/, "").replace(/\.json$/, "");
  const rows = JSON.parse(fs.readFileSync(path.join(input, file), "utf8"));
  for (const item of rows) {
    const id = Number(item["Item ID"]);
    if (!Number.isFinite(id) || id <= 0) continue;
    const previous = records.get(id);
    const chosenCategory = !previous || (rank.get(category) ?? 0) > (rank.get(previous.category) ?? 0) ? category : previous.category;
    records.set(id, { category: chosenCategory, item: { ...(previous?.item || {}), ...item } });
  }
}
const categories = [...new Set([...records.values()].map((entry) => entry.category))].sort();
const categoryIds = new Map(categories.map((name, index) => [name, index]));
const rows = [...records.entries()].sort((a, b) => a[0] - b[0]).map(([id, entry]) => {
  const values = FIELDS.map((field) => entry.item[field] ?? null);
  while (values.length && values.at(-1) == null) values.pop();
  return [id, categoryIds.get(entry.category), values];
});
const payload = {
  format: 1,
  source: "natan-dot-com/Terraria-Dataset",
  commit: "51d0b5f1e83c971d16d76e7cbb1364cb3f07d19e",
  sourceDate: "2022-01-31",
  fields: FIELDS,
  categories,
  rows,
  coverage: {
    records: rows.length,
    tooltips: rows.filter((row) => row[2][0]).length,
    fishingPoles: rows.filter((row) => row[2][7]).length,
    poweredTools: rows.filter((row) => row[2].slice(4, 7).some((value) => value && value !== "0%" )).length
  }
};
const banner = `/* Compact semantic vanilla item metadata. Generated by scripts/build-vanilla-meta.mjs.\n * Source: ${payload.source}@${payload.commit}\n */\n`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, `${banner}window.CALAMITY_VANILLA_META=${JSON.stringify(payload)};\n`);
console.log(`Wrote ${rows.length} vanilla metadata rows (${payload.coverage.tooltips} tooltips, ${payload.coverage.fishingPoles} fishing poles) to ${output}`);
