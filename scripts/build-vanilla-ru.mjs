#!/usr/bin/env node
import fs from "node:fs";
import vm from "node:vm";

const [enPath, ruPath, nameDbPath, treePath = "calamity-codex/js/vanilla-tree.js", outPath = "calamity-codex/js/vanilla-ru.js"] = process.argv.slice(2);
if (!enPath || !ruPath || !nameDbPath) {
  console.error("Usage: node scripts/build-vanilla-ru.mjs <en-US.Items.json> <ru-RU.Items.json> <Iteminfo.data.nameDB.json> [vanilla-tree.js] [out.js]");
  process.exit(1);
}

const enPayload = JSON.parse(fs.readFileSync(enPath, "utf8"));
const ruPayload = JSON.parse(fs.readFileSync(ruPath, "utf8"));
const en = enPayload.ItemName || {};
const ru = ruPayload.ItemName || {};
const enTooltips = enPayload.ItemTooltip || {};
const ruTooltips = ruPayload.ItemTooltip || {};
const itemNames = JSON.parse(fs.readFileSync(nameDbPath, "utf8"));
// Current official wiki wording fixes a handful of obsolete/broken in-game
// strings while the original game-localization name remains recoverable from
// the pinned source. Add only manually verified exact ID corrections here.
const NAME_CORRECTIONS = {
  4325: "«Завлекатель приманки»"
};
function resolveLocalization(value, payload) {
  let text = String(value || "");
  for (let pass = 0; pass < 4 && /\{\$[^}]+\}/.test(text); pass += 1) {
    text = text.replace(/\{\$([^.}]+)\.([^}]+)\}/g, (match, section, key) => payload?.[section]?.[key] ?? match);
  }
  return text.replace(/\s*\n\s*/g, " ").replace(/\s+/g, " ").trim();
}
const internalById = itemNames.itemInternalNameFromId || {};
const context = { window: {} };
context.window.window = context.window;
vm.runInNewContext(fs.readFileSync(treePath, "utf8"), context, { filename: treePath });
const tree = context.window.CALAMITY_VANILLA_TREE_INDEX;
if (!tree || !Array.isArray(tree.items)) throw new Error("Vanilla tree index was not loaded");

const maxItemId = tree.format === 2
  ? Number(tree.firstItemId || 1) + tree.items.length - 1
  : Math.max(...tree.items.map((row) => Number(row[0])));
const names = Array(maxItemId + 1).fill(null);
const tooltips = Array(maxItemId + 1).fill(null);
let officialCount = 0;
let tooltipCount = 0;
for (const [index, row] of tree.items.entries()) {
  const id = tree.format === 2 ? Number(tree.firstItemId || 1) + index : Number(row[0]);
  const internalName = internalById[String(id)];
  const englishName = internalName && en[internalName];
  const russianName = internalName && ru[internalName];
  // Проверяем обе официальные локали: служебные ID без ItemName не должны
  // получать выдуманное имя только потому, что присутствуют в ID-дампе.
  if (!englishName || !russianName) continue;
  names[id] = NAME_CORRECTIONS[id] || russianName;
  officialCount += 1;
  const englishTooltip = internalName && enTooltips[internalName];
  const russianTooltip = internalName && ruTooltips[internalName];
  if (englishTooltip && russianTooltip) {
    const resolvedTooltip = resolveLocalization(russianTooltip, ruPayload);
    if (resolvedTooltip && !/\{\$[^}]+\}/.test(resolvedTooltip)) {
      tooltips[id] = resolvedTooltip;
      tooltipCount += 1;
    }
  }
}

const payload = {
  format: 2,
  source: "Official Terraria ru-RU ItemName localization",
  mirror: "dsafxP/terrariamuzz",
  commit: "c95e85de00dd7e5a02478a2ffa82cc3a5131042c",
  officialCount,
  tooltipCount,
  names,
  tooltips
};
const banner = `/* Generated by scripts/build-vanilla-ru.mjs.\n * Official Terraria en-US/ru-RU ItemName localization and ID map mirrored by\n * dsafxP/terrariamuzz at c95e85de00dd7e5a02478a2ffa82cc3a5131042c.\n */\n`;
fs.writeFileSync(outPath, `${banner}window.CALAMITY_VANILLA_RU=${JSON.stringify(payload)};\n`);
console.log(`Wrote ${payload.officialCount} official vanilla Russian names and ${payload.tooltipCount} translated tooltips keyed by stable Terraria item ID to ${outPath}`);
